function hash(s: string): number {
  let h = 0
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0
  return Math.abs(h)
}

/** 상황에 맞는 대사 하나. seed 가 같으면 같은 줄이라 화면을 다시 그려도 바뀌지 않는다 */
export function personaScript(persona: Persona, kind: ScriptKind, vars: ScriptVars, seed: string): string | null {
  if (persona === 'default') return null
  const lines = SCRIPTS[persona][kind]
  const line = lines[hash(`${seed}|${kind}`) % lines.length]
  return line.replace(/\{(\w+)\}/g, (_, k: keyof ScriptVars) => String(vars[k]))
}

